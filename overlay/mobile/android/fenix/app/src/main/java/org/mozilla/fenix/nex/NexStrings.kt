        "es" to ES, "pt" to PT, "fr" to FR, "de" to DE, "it" to IT, "ru" to RU, "tr" to TR,
        "ar" to AR, "hi" to HI, "in" to ID, "id" to ID, "ja" to JA, "ko" to KO, "zh" to ZH,
    )

    private fun table(context: Context): Map<String, String> {
        val lang = context.resources.configuration.locales[0].language
        return BY_LANG[lang] ?: EN
    }

    /** Translated text for [key] (English fallback), formatted with [args] if any. */
    fun get(context: Context, key: String, vararg args: Any): String {
        val raw = table(context)[key] ?: EN[key] ?: key
        return if (args.isEmpty()) raw else String.format(context.resources.configuration.locales[0], raw, *args)
    }
}
