"""Render all branding assets from one SVG source (icon option B: shield + crossed eye).

Outputs:
  branding/release/res/...      launcher icons, wordmarks, search widget (replace Firefox's)
  branding/main/res/drawable/   adaptive-icon foreground (also used for every alternate icon)
  branding/store/icon-512.png   Google Play icon (512x512, full square, no shadow)
Run:  python3 branding/build_assets.py
"""
import io
import os

import cairosvg
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
REL = os.path.join(HERE, "release", "res")
MAIN = os.path.join(HERE, "main", "res")
STORE = os.path.join(HERE, "store")

MINT = "#3DF5B0"
INK = "#0A0D1C"
APP_LABEL = "Ad Blocker"

SHIELD = "M256 92l140 56v92c0 88-58 156-140 182C174 396 116 328 116 240v-92z"
EYE = "M172 250c26-40 54-60 84-60s58 20 84 60c-26 40-54 60-84 60s-58-20-84-60z"


def mark(size_px, rounded=None, circle=False):
    """The icon artwork as SVG text (512 viewBox)."""
    clip = ""
    if circle:
        clip = '<clipPath id="c"><circle cx="256" cy="256" r="256"/></clipPath>'
    elif rounded:
        clip = f'<clipPath id="c"><rect width="512" height="512" rx="{rounded}"/></clipPath>'
    g_open = '<g clip-path="url(#c)">' if clip else "<g>"
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{size_px}" height="{size_px}" viewBox="0 0 512 512">
<defs>{clip}</defs>{g_open}
<rect width="512" height="512" fill="{MINT}"/>
<path d="{SHIELD}" fill="{INK}"/>
<path d="{EYE}" fill="none" stroke="{MINT}" stroke-width="20" stroke-linejoin="round"/>
<circle cx="256" cy="250" r="22" fill="{MINT}"/>
<path d="M176 330l160-160" stroke="{INK}" stroke-width="34" stroke-linecap="round"/>
<path d="M176 330l160-160" stroke="{MINT}" stroke-width="18" stroke-linecap="round"/>
</g></svg>"""


def wordmark(w, h, dark_text):
    """Shield mark + app label, transparent background."""
    s = h / 512.0
    text_color = "#F4F6FF" if dark_text is False else INK
    font_px = int(h * 0.42)
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">
<g transform="scale({s})">
<path d="{SHIELD}" fill="{MINT}"/>
<path d="M176 330l160-160" stroke="{INK}" stroke-width="30" stroke-linecap="round"/>
</g>
<text x="{int(h * 0.92)}" y="{int(h * 0.66)}" font-family="Inter, DejaVu Sans, sans-serif" font-weight="700"
 font-size="{font_px}" fill="{text_color}">{APP_LABEL}</text>
</svg>"""


def text_only(w, h, color):
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">
<text x="0" y="{int(h * 0.75)}" font-family="Inter, DejaVu Sans, sans-serif" font-weight="700"
 font-size="{int(h * 0.8)}" fill="{color}" textLength="{w - 4}" lengthAdjust="spacingAndGlyphs">{APP_LABEL}</text>
</svg>"""


def save(svg, path, fmt="WEBP"):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    png = cairosvg.svg2png(bytestring=svg.encode())
    img = Image.open(io.BytesIO(png)).convert("RGBA")
    if fmt == "PNG":
        img.save(path, "PNG")
    else:
        img.save(path, "WEBP", lossless=True)


def adaptive_foreground_xml():
    """VectorDrawable for the adaptive icon foreground (108dp canvas, art inside the 66dp safe zone)."""
    s = 0.17
    tx = 54 - 256 * s
    ty = 54 - 257 * s
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by branding/build_assets.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
  <group android:scaleX="{s}" android:scaleY="{s}" android:translateX="{tx:.2f}" android:translateY="{ty:.2f}">
    <path android:fillColor="{INK}" android:pathData="{SHIELD}"/>
    <path android:strokeColor="{MINT}" android:strokeWidth="20" android:strokeLineJoin="round" android:pathData="{EYE}"/>
    <path android:fillColor="{MINT}" android:pathData="M234,250a22,22 0,1 0,44 0a22,22 0,1 0,-44 0z"/>
    <path android:strokeColor="{INK}" android:strokeWidth="34" android:strokeLineCap="round" android:pathData="M176,330L336,170"/>
    <path android:strokeColor="{MINT}" android:strokeWidth="18" android:strokeLineCap="round" android:pathData="M176,330L336,170"/>
  </group>
</vector>
"""


def main():
    # Launcher icons (legacy, pre-adaptive): rounded square + round.
    for dpi, px in {"mdpi": 48, "hdpi": 76, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
        save(mark(px, rounded=154), f"{REL}/mipmap-{dpi}/ic_launcher.webp")
        save(mark(px, circle=True), f"{REL}/mipmap-{dpi}/ic_launcher_round.webp")

    # Wordmarks shown inside the app (sizes match the Firefox files they replace).
    sizes = {"mdpi": (277, 80), "hdpi": (414, 120), "xhdpi": (552, 160), "xxhdpi": (828, 239), "xxxhdpi": (1103, 319)}
    for dpi, (w, h) in sizes.items():
        save(wordmark(w, h, dark_text=True), f"{REL}/drawable-{dpi}/ic_logo_wordmark_normal.webp")
        save(wordmark(w, h, dark_text=False), f"{REL}/drawable-{dpi}/ic_logo_wordmark_private.webp")
    save(mark(160), f"{REL}/drawable-nodpi/ic_wordmark_logo.webp")
    save(text_only(419, 93, INK), f"{REL}/drawable-nodpi/ic_wordmark_text_normal.webp")
    save(text_only(419, 93, "#F4F6FF"), f"{REL}/drawable-nodpi/ic_wordmark_text_private.webp")
    save(wordmark(1014, 180, dark_text=True), f"{REL}/drawable-hdpi/fenix_search_widget.webp")

    # Adaptive icon: foreground vector + mint background colour.
    fg = adaptive_foreground_xml()
    for d in (f"{REL}/drawable", f"{MAIN}/drawable"):
        os.makedirs(d, exist_ok=True)
        with open(f"{d}/ic_launcher_foreground.xml", "w") as f:
            f.write(fg)
    os.makedirs(f"{REL}/values", exist_ok=True)
    with open(f"{REL}/values/colors.xml", "w") as f:
        f.write(f"""<?xml version="1.0" encoding="utf-8"?>
<resources>
    <color name="ic_launcher_background">{MINT}</color>
</resources>
""")

    # Google Play listing icon: 512x512 full square PNG (Play applies the mask and shadow).
    save(mark(512), f"{STORE}/icon-512.png", fmt="PNG")
    print("Assets written.")


if __name__ == "__main__":
    main()
